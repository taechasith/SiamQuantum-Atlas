export function t(text: string): string {
  if (lang.value === 'en') return text
  return th[text] ?? text
}

export function setLang(next: Lang): void {
  lang.value = next
  localStorage.setItem(STORAGE_KEY, next)
}

export function toggleLang(): void {
  setLang(lang.value === 'th' ? 'en' : 'th')
}
